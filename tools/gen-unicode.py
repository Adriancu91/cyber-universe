#!/usr/bin/env python3
"""P6-27b: writes user/src/unicode.rs, the three character classes the KGR1 tokenizer needs (specification
`integrare/kronos/format_greutati.md`, "Pre-tokenizarea"), taken from this Python's own str methods:

  letter  = isalnum() and not isdecimal() (and not "_", which is never alnum)
  decimal = isdecimal()
  space   = isspace()

Run: python3 tools/gen-unicode.py > user/src/unicode.rs  (the Unicode version is written in the file header).
"""
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000 + 1):
        ok = cp < 0x110000 and not (0xD800 <= cp <= 0xDFFF) and pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    # Surrogates are not Rust chars: join ranges split only by them.
    merged = []
    for lo, hi in out:
        if merged and merged[-1][1] == 0xD7FF and lo == 0xE000:
            merged[-1] = (merged[-1][0], hi)
        else:
            merged.append((lo, hi))
    return merged


def table(name, rs):
    lines = [f"pub static {name}: [(u32, u32); {len(rs)}] = ["]
    row = []
    for lo, hi in rs:
        row.append(f"(0x{lo:X}, 0x{hi:X})")
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("];")
    return "\n".join(lines)


def main():
    letter = ranges(lambda c: c.isalnum() and not c.isdecimal() and c != "_")
    decimal = ranges(lambda c: c.isdecimal())
    space = ranges(lambda c: c.isspace())
    out = sys.stdout
    out.write(
        "//! Character classes of the KGR1 tokenizer (P6-27b), generated by `tools/gen-unicode.py` from Python "
        f"{sys.version.split()[0]}\n//! (Unicode {unicodedata.unidata_version}). Do not edit by hand.\n"
        "//! letter = isalnum() && !isdecimal(); decimal = isdecimal(); space = isspace(). Sorted, inclusive ranges.\n\n"
    )
    out.write(f"pub const UNICODE_VERSION: &str = \"{unicodedata.unidata_version}\";\n\n")
    out.write(table("LETTER", letter) + "\n\n" + table("DECIMAL", decimal) + "\n\n" + table("SPACE", space) + "\n\n")
    out.write(
        "fn within(t: &[(u32, u32)], c: char) -> bool {\n"
        "    let c = c as u32;\n"
        "    t.binary_search_by(|&(lo, hi)| {\n"
        "        if hi < c {\n            core::cmp::Ordering::Less\n"
        "        } else if lo > c {\n            core::cmp::Ordering::Greater\n"
        "        } else {\n            core::cmp::Ordering::Equal\n        }\n"
        "    })\n    .is_ok()\n}\n\n"
        "/// Python: `c.isalnum() and not c.isdecimal()`.\n"
        "pub fn is_letter(c: char) -> bool {\n    if c.is_ascii() {\n        return c.is_ascii_alphabetic();\n    }\n"
        "    within(&LETTER, c)\n}\n\n"
        "/// Python: `c.isdecimal()` (Unicode category Nd).\n"
        "pub fn is_decimal(c: char) -> bool {\n    if c.is_ascii() {\n        return c.is_ascii_digit();\n    }\n"
        "    within(&DECIMAL, c)\n}\n\n"
        "/// Python: `c.isspace()`.\n"
        "pub fn is_space(c: char) -> bool {\n    within(&SPACE, c)\n}\n"
    )


main()
